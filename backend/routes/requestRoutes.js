import express from 'express';
import { createRequest, getMyRequests, getProfessorRequests, getProfessorActiveRequest, getRequestById, updateVerification, updateRequestStatus, generateDraft, uploadLOR, downloadLOR, downloadDraft, downloadVerificationDocument, getAllRequests, deletePendingRequest, updateStudentRequestDocuments } from '../controllers/requestController.js';
import { protect, authorize, requireVerifiedProfessor } from '../middleware/authMiddleware.js';
import { uploadPdf, uploadRequestDocs } from '../middleware/uploadMiddleware.js';
const router = express.Router();
router.post('/', protect, authorize('student'), uploadRequestDocs, createRequest);
router.get('/mine', protect, authorize('student'), getMyRequests);
router.get('/professor/active', protect, authorize('professor'), requireVerifiedProfessor, getProfessorActiveRequest);
router.get('/professor', protect, authorize('professor'), requireVerifiedProfessor, getProfessorRequests);
router.get('/all', protect, authorize('admin'), getAllRequests);
router.delete('/:id', protect, deletePendingRequest);
router.patch('/:id/documents', protect, authorize('student'), uploadRequestDocs, updateStudentRequestDocuments);
router.get('/:id/documents/:documentId', protect, downloadVerificationDocument);
router.get('/:id/draft', protect, downloadDraft);
router.get('/:id/file', protect, downloadLOR);
router.get('/:id', protect, getRequestById);
router.patch('/:id/verification', protect, authorize('professor'), requireVerifiedProfessor, updateVerification);
router.patch('/:id/status', protect, authorize('professor'), requireVerifiedProfessor, updateRequestStatus);
router.patch('/:id/draft', protect, authorize('professor'), requireVerifiedProfessor, generateDraft);
router.post('/:id/file', protect, authorize('professor'), requireVerifiedProfessor, uploadPdf.single('lorFile'), uploadLOR);
export default router;
